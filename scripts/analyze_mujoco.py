"""Analysis of the MuJoCo experiment, written BEFORE results existed (fixed rules for P1-P7).

Per regime and planner: mean cost ratio vs forward (pooled over seeds, episodes paired by schedule), 95% paired
bootstrap CI of the ratio over episodes x seeds. 'beats X' := upper CI of ratio(planner/X) < 1;
'worse than X' := lower CI > 1; otherwise 'tie'. Writes a LaTeX table to papers/latent-hindsight-planning/generated/.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from wmi.harness import load_results  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def paired_ratio(a, b, rng, n=4000):
    a, b = np.asarray(a), np.asarray(b)
    idx = rng.integers(0, len(a), (n, len(a)))
    r = a[idx].mean(1) / b[idx].mean(1)
    return float(a.mean() / b.mean()), [float(x) for x in np.quantile(r, [0.025, 0.975])]


def verdict(ci):
    return "beats" if ci[1] < 1 else ("worse" if ci[0] > 1 else "tie")


def main():
    runs = load_results("mujoco_hindsight")
    if not runs:
        print("no results"); return
    rng = np.random.default_rng(0)
    regs = list(runs[0]["metrics"]["regimes"])
    planners = list(runs[0]["metrics"]["regimes"][regs[0]])
    pooled = {r: {p: np.concatenate([np.array(x["metrics"]["regimes"][r][p]["per_episode_cost"]) for x in runs])
                  for p in planners} for r in regs}
    tab = {}
    for r in regs:
        tab[r] = {p: paired_ratio(pooled[r][p], pooled[r]["forward"], rng) for p in planners}
    def cmp(r, p, q):
        return verdict(paired_ratio(pooled[r][p], pooled[r][q], rng)[1])
    hs = ["online_sgd", "hindsight_posterior", "hybrid", "hindsight_latent"]
    checks = {
        "P1 persistent: all hindsight beat forward": all(cmp(r, p, "forward") == "beats" for r in ("gain", "wind", "both") for p in hs),
        "P1b latent ~ oracle (tie or beats) on gain/wind/both": all(cmp(r, "hindsight_latent", "oracle_latent") in ("tie", "beats") for r in ("gain", "wind", "both")),
        "P2 wind: residual beats forward": cmp("wind", "residual", "forward") == "beats",
        "P2b wind: posterior beats residual": cmp("wind", "hindsight_posterior", "residual") == "beats",
        "P3 gain: posterior beats residual": cmp("gain", "hindsight_posterior", "residual") == "beats",
        "P3b ood_gain: posterior and latent beat residual": all(cmp("ood_gain", p, "residual") == "beats" for p in ("hindsight_posterior", "hindsight_latent")),
        "P4 fresh: no hindsight planner beats forward": all(cmp("fresh", p, "forward") != "beats" for p in hs),
        "P4b fresh: residual worse than forward": cmp("fresh", "residual", "forward") == "worse",
        "P5 none: residual worse than forward": cmp("none", "residual", "forward") == "worse",
        "P6 switching: posterior, latent, sgd beat forward": all(cmp("switching", p, "forward") == "beats" for p in ("hindsight_posterior", "hindsight_latent", "online_sgd")),
        "P7 gain & ood_gain: hybrid beats online_sgd": all(cmp(r, "hybrid", "online_sgd") == "beats" for r in ("gain", "ood_gain")),
    }
    for r in regs:
        print(r, {p: (round(v[0], 3), [round(c, 3) for c in v[1]]) for p, v in tab[r].items()})
    print()
    for k, v in checks.items():
        print(("SUPPORTED " if v else "NOT SUPPORTED ") + k)
    commits = sorted({x["provenance"]["git_commit"][:7] for x in runs})
    dirty = any(x["provenance"]["git_dirty"] for x in runs)
    lines = [f"% generated by scripts/analyze_mujoco.py; seeds={sorted(x['provenance']['config']['seed'] for x in runs)}; commits={commits}; dirty={dirty}\n",
             "\\begin{tabular}{l" + "c" * (len(planners) - 1) + "}\n\\toprule\n",
             "Regime & " + " & ".join(p.replace("_", "\\_") for p in planners if p != "forward") + " \\\\\n\\midrule\n"]
    for r in regs:
        cells = []
        for p in planners:
            if p == "forward":
                continue
            m, ci = tab[r][p]
            mark = {"beats": "$\\downarrow$", "worse": "$\\uparrow$", "tie": ""}[verdict(ci)]
            cells.append(f"{m:.3f}{mark}")
        lines.append(r.replace("_", "\\_") + " & " + " & ".join(cells) + " \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    out = ROOT / "papers" / "latent-hindsight-planning" / "generated" / "mujoco_table.tex"
    out.write_text("".join(lines))
    (ROOT / "papers" / "latent-hindsight-planning" / "generated" / "mujoco_predictions.txt").write_text(
        "\n".join(("SUPPORTED " if v else "NOT SUPPORTED ") + k for k, v in checks.items()) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
