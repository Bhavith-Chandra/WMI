"""Build LaTeX tables for the papers from results/*.json ONLY.

Papers \\input the files in papers/*/generated/. Never type a number into a .tex file.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from wmi.harness import load_results  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def ms(vals, fmt="{:.3f}"):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    if len(vals) == 1:
        return fmt.format(vals[0])
    return f"{fmt.format(np.mean(vals))} $\\pm$ {fmt.format(np.std(vals, ddof=1))}"


def provenance_note(runs):
    commits = sorted({r["provenance"]["git_commit"][:7] for r in runs if r["provenance"]["git_commit"]})
    dirty = any(r["provenance"]["git_dirty"] for r in runs)
    seeds = sorted(r["provenance"]["config"]["seed"] for r in runs)
    return f"% generated by scripts/make_tables.py; seeds={seeds}; commits={commits}; dirty={dirty}\n"


def probe_table():
    runs = load_results("probes")
    if not runs:
        return None
    keys = list(runs[0]["metrics"]["probes"].keys())
    lines = [provenance_note(runs),
             "\\begin{tabular}{lllccccc}\n\\toprule\n",
             "Model & Site & Target & Real & Control task & Selectivity & Shuffled & Majority \\\\\n\\midrule\n"]
    for k in keys:
        m, site, tgt = k.split("/")
        P = [r["metrics"]["probes"][k] for r in runs]
        lines.append(f"{m} & {site} & {tgt.replace('_', chr(92) + '_')} & {ms([p['real']['test'] for p in P])} & "
                     f"{ms([p['control_task']['test'] for p in P])} & {ms([p['selectivity'] for p in P])} & "
                     f"{ms([p['shuffled']['test'] for p in P])} & {ms([p['majority']['test'] for p in P])} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")

    iv = ["\n" + provenance_note(runs), "\\begin{tabular}{lllcc}\n\\toprule\n",
          "Intervention & Direction & $\\alpha$ & $p(\\text{key at cell})$ & Blocked-channel acc. \\\\\n\\midrule\n"]
    conds = runs[0]["metrics"]["interventions"]["conditions"]
    for name in conds:
        for dname in ("probe", "diff_means", "random"):
            for i, c in enumerate(conds[name][dname]):
                vals = [r["metrics"]["interventions"]["conditions"][name][dname][i] for r in runs]
                iv.append(f"{name.replace('_', chr(92) + '_')} & {dname.replace('_', chr(92) + '_')} & {c['alpha']:g} & "
                          f"{ms([v['p_key_at_cell'] for v in vals])} & {ms([v['blocked_channel_acc'] for v in vals])} \\\\\n")
        iv.append("\\midrule\n")
    I = [r["metrics"]["interventions"] for r in runs]
    iv.append(f"\\multicolumn{{5}}{{l}}{{$D$ = {ms([i['D_between_class'] for i in I])}; "
              f"cos(probe, diff-means) = {ms([i['cos_probe_vs_diff_means'] for i in I])}}} \\\\\n")
    iv.append("\\bottomrule\n\\end{tabular}\n")
    return "".join(lines), "".join(iv)


def planning_table():
    runs = load_results("planning")
    if not runs:
        return None
    lines = [provenance_note(runs), "\\begin{tabular}{lcc}\n\\toprule\n",
             "Policy & Success rate & Excess steps (successes) \\\\\n\\midrule\n"]
    for pol in ("random", "cem_l2", "cem_hindsight"):
        P = [r["metrics"]["planning"][pol] for r in runs]
        lines.append(f"{pol.replace('_', chr(92) + '_')} & {ms([p['success_rate'] for p in P])} & "
                     f"{ms([p['mean_excess_steps_on_success'] for p in P], '{:.2f}')} \\\\\n")
    mq = [r["metrics"]["model_quality"] for r in runs]
    lines.append("\\midrule\n")
    lines.append(f"\\multicolumn{{3}}{{l}}{{Spearman($d_\\theta$, shortest path) = {ms([m['spearman_dist_vs_shortest_path'] for m in mq])}; "
                 f"Spearman($\\ell_2$, shortest path) = {ms([m['spearman_l2_vs_shortest_path'] for m in mq])}}} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    return "".join(lines)


def theory_table():
    runs = load_results("theory_hindsight")
    if not runs:
        return None
    P = ("forward", "residual", "hindsight_bayes", "hindsight_forget")
    lines = [provenance_note(runs), "\\begin{tabular}{l" + "c" * len(P) + "c}\n\\toprule\n",
             "Regime & " + " & ".join(p.replace("_", chr(92) + "_") for p in P) + " & $t\\cdot$excess (hindsight) \\\\\n\\midrule\n"]
    for reg in ("persistent", "persistent_additive", "persistent_gain", "fresh", "switching", "none"):
        cells = [ms([r["metrics"][reg][p]["cum_regret_T"] for r in runs], "{:.1f}") for p in P]
        tq = ms([r["metrics"][reg]["hindsight_bayes"]["t_times_excess_q4"] for r in runs], "{:.2f}")
        lines.append(reg.replace("_", chr(92) + "_") + " & " + " & ".join(cells) + f" & {tq} \\\\\n")
    cf = runs[0]["metrics"]["closed_form"]
    cfg = runs[0]["provenance"]["config"]
    lines.append("\\midrule\n")
    lines.append(f"\\multicolumn{{6}}{{l}}{{Closed forms: $c_F T$ = {cf['forward_excess_per_step'] * cfg['T']:.1f}; "
                 f"residual (additive) $\\sigma^2 T$ = {cf['residual_excess_per_step_additive_only'] * cfg['T']:.1f}; "
                 f"$\\sigma^2 d$ = {2 * cfg['sigma'] ** 2:.2f}; $T$ = {cfg['T']}, $M$ = {cfg['M']}}} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    return "".join(lines)


def main():
    th = theory_table()
    if th:
        (ROOT / "papers" / "latent-hindsight-planning" / "generated" / "theory_table.tex").write_text(th)
    pt = probe_table()
    if pt:
        for paper in ("wmi-tutorial", "latent-hindsight-planning"):
            g = ROOT / "papers" / paper / "generated"
            g.mkdir(parents=True, exist_ok=True)
            (g / "probe_table.tex").write_text(pt[0])
            (g / "intervention_table.tex").write_text(pt[1])
    pl = planning_table()
    if pl:
        for paper in ("latent-hindsight-planning", "wmi-tutorial"):
            (ROOT / "papers" / paper / "generated" / "planning_table.tex").write_text(pl)
    print("probe tables:", bool(pt), "planning table:", bool(pl), "theory table:", bool(th))


if __name__ == "__main__":
    main()
